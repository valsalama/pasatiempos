  function limpiar(p) {
    return String(p).toUpperCase()
      .replace(/Ñ/g, '\u0001')
      .normalize('NFD').replace(/[̀-ͯ]/g, '')
      .replace(/\u0001/g, 'Ñ')
      .replace(/[^A-ZÑ]/g, '');
  }

  // Se juntan todas las definiciones de cada palabra (las que empiezan con * son las difíciles)
  const porPalabra = new Map();
  DATOS.forEach((fila) => {
    if (!Array.isArray(fila) || fila.length < 2) return;
    const p = limpiar(fila[0]);
    if (p.length < 3 || p.length > 9) return;
    if (!porPalabra.has(p)) porPalabra.set(p, { p, d: [], dificiles: [] });
    const e = porPalabra.get(p);
    fila.slice(1).forEach((d) => {
      if (typeof d !== 'string' || d.trim().length < 2) return;
      const dificil = d.trim().charAt(0) === '*';
      const texto = d.trim().replace(/^\*\s*/, '');
      // la definición no puede contener la palabra buscada, ni repetirse
      if (limpiar(texto).includes(p)) return;
      const lista = dificil ? e.dificiles : e.d;
      if (!lista.includes(texto) && !e.d.includes(texto) && !e.dificiles.includes(texto)) lista.push(texto);
    });
  });

  const lista = [];
  porPalabra.forEach((e) => { if (e.d.length || e.dificiles.length) lista.push(e); });

  global.PalabrasCrucigrama = { lista, limpiar };
